"""Сценарий видео «Весь Python за один урок».

Каждая сцена — словарь:
  kind     — "title" (заставка), "bullets" (тезисы) или "code" (редактор + терминал)
  chapter  — название главы (для bullets/code)
  steps    — шаги; каждый шаг — одна фраза диктора

Шаг создаётся функцией T(text, code=None, ...):
  text  — фраза. Вставка {print|принт} значит: в субтитрах «print», а диктор
          произносит «принт». Так английские слова звучат естественно.
  code  — блок кода, который печатается на экране, пока звучит фраза.
  cont  — приклеить блок к предыдущему без пустой строки.
  hl    — (первая, последняя) строка кода, которую подсветить во время фразы.
  bullet — тезис для сцен типа bullets.
  indent — сдвинуть блок на N уровней (например, методы внутри класса).
"""
import textwrap


def T(text, code=None, cont=False, hl=None, bullet=None, indent=0):
    if code is not None:
        code = textwrap.indent(textwrap.dedent(code).strip("\n"), "    " * indent)
    return dict(text=text, code=code, cont=cont, hl=hl, bullet=bullet)


